/** Insert values once so their text, braces and punctuation remain unchanged. */
export function rt(language, key, values = {}) {
  const dictionary = REFINEMENT_MESSAGES[language] ?? REFINEMENT_MESSAGES.en;
  const template = dictionary[key] ?? REFINEMENT_MESSAGES.en[key] ?? String(key);
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (token, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : token,
  );
}
