export function combinationCopy(locale, key, zh, en, n) {
  const index = languages.indexOf(locale);
  let text = locale === 'zh-CN' ? zh : en;
  if (index >= 0)
    text =
      key === 'previous' ? words.round[index] + ' · ' + words.repeat[index] : words[key][index];
  return text.replaceAll('{n}', String(n));
}

